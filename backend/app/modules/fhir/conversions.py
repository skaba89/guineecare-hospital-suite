def admission_to_fhir(admission, patient=None):
    """Convertit une Admission en ressource FHIR Encounter R4.

    Statuts mappés (basés sur le modèle Admission réel) :
    - OPEN → in-progress (admission active)
    - CLOSED → finished (patient sorti)
    - CANCELLED → cancelled
    """
    status_map = {
        "OPEN": "in-progress",
        "CLOSED": "finished",
        "ACTIVE": "in-progress",
        "DISCHARGED": "finished",
        "SCHEDULED": "planned",
        "CANCELLED": "cancelled",
    }
    admission_status = getattr(admission, "status", "OPEN") or "OPEN"
    fhir_status = status_map.get(admission_status.upper(), "unknown")

    # Class mapping (AMBULATORY/EMERGENCY/INPATIENT/etc.)
    class_map = {
        "ROUTINE": ("AMB", "ambulatory"),
        "EMERGENCY": ("EMER", "emergency"),
        "URGENT": ("EMER", "emergency"),
        "SURGERY": ("SURG", "surgical"),
        "MATERNITY": ("MAT", "maternity"),
    }
    admission_type = getattr(admission, "admission_type", "ROUTINE") or "ROUTINE"
    class_code, class_display = class_map.get(admission_type, ("AMB", "ambulatory"))

    fhir = {
        "resourceType": "Encounter",
        "id": admission.id,
        "meta": _meta("Encounter", admission.id, getattr(admission, "admitted_at", None)),
        "status": fhir_status,
        "class": {
            "system": "http://terminology.hl7.org/CodeSystem/v3-ActCode",
            "code": class_code,
            "display": class_display,
        },
        "subject": _reference("Patient", admission.patient_id),
    }

    if admission.facility_id:
        fhir["serviceProvider"] = {"reference": f"Organization/{admission.facility_id}"}

    admitted_at = getattr(admission, "admitted_at", None)
    closed_at = getattr(admission, "closed_at", None)
    if admitted_at:
        period = {"start": _iso(admitted_at)}
        if closed_at:
            period["end"] = _iso(closed_at)
        fhir["period"] = period

    return fhir


