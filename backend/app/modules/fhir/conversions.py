def imaging_result_to_fhir(result, patient_id):
    """Convertit un ImagingResult en ressource FHIR DiagnosticReport R4.

    Statuts mappés :
    - DRAFT → preliminary
    - VALIDATED → final
    - CANCELLED → cancelled
    """
    status = getattr(result, "status", None) or "VALIDATED"
    status_map = {
        "DRAFT": "preliminary",
        "VALIDATED": "final",
        "CANCELLED": "cancelled",
    }
    fhir_status = status_map.get(status.upper(), "final")

    fhir = {
        "resourceType": "DiagnosticReport",
        "id": result.id,
        "meta": _meta("DiagnosticReport", result.id, result.created_at),
        "status": fhir_status,
        "code": _codeable_concept(LOINC_SYSTEM, "18748-4", "Diagnostic imaging report"),
        "subject": _reference("Patient", patient_id),
    }

    # Conclusion
    conclusion_parts = []
    findings = getattr(result, "findings", None)
    if findings:
        conclusion_parts.append(f"Findings: {findings}")
    conclusion = getattr(result, "conclusion", None)
    if conclusion:
        conclusion_parts.append(f"Conclusion: {conclusion}")
    if conclusion_parts:
        fhir["conclusion"] = "\n".join(conclusion_parts)

    # Effective date
    reported_at = getattr(result, "reported_at", None)
    if reported_at:
        fhir["effectiveDateTime"] = _iso(reported_at)
    elif hasattr(result, "created_at"):
        fhir["effectiveDateTime"] = _iso(result.created_at)

    return fhir


