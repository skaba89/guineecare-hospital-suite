# ClinicalNote (PRESCRIPTION) → FHIR MedicationRequest
# ---------------------------------------------------------------------------

def prescription_to_fhir(note, patient_id):
    """Convertit une ClinicalNote (note_type=PRESCRIPTION) en FHIR MedicationRequest.

    Le champ `content` contient la prescription en texte libre. En v1.6 on ne
    parse pas le contenu — on le met dans `medicationCodeableConcept.text`.
    """
    note_status = getattr(note, "status", None) or "ACTIVE"
    status_map = {
        "ACTIVE": "active",
        "COMPLETED": "completed",
        "CANCELLED": "cancelled",
        "DRAFT": "draft",
    }
    fhir_status = status_map.get(note_status.upper(), "active")

    fhir = {
        "resourceType": "MedicationRequest",
        "id": note.id,
        "meta": _meta("MedicationRequest", note.id, note.created_at),
        "status": fhir_status,
        "intent": "order",
        "subject": _reference("Patient", patient_id),
        "authoredOn": _iso(note.created_at),
    }

    content = getattr(note, "content", None)
    if content:
        fhir["medicationCodeableConcept"] = {"text": content[:500]}

    author_id = getattr(note, "author_id", None)
    if author_id:
        fhir["requester"] = {"reference": f"Practitioner/{author_id}"}

    return fhir


