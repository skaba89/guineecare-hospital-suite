GUINEECARE_SYSTEM = "https://guineecare.gn/fhir"
PATIENT_NUMBER_SYSTEM = "https://guineecare.gn/identifiers/patient-number"
NATIONAL_ID_SYSTEM = "https://guineecare.gn/identifiers/national-id"
ENCOUNTER_NUMBER_SYSTEM = "https://guineecare.gn/identifiers/encounter"
LOINC_SYSTEM = "http://loinc.org"
SNOMED_SYSTEM = "http://snomed.info/sct"

# Mapping constantes vitales → codes LOINC
VITAL_LOINC = {
    "HEART_RATE": ("8867-4", "Heart rate"),
    "BLOOD_PRESSURE_SYSTOLIC": ("8480-6", "Systolic blood pressure"),
    "BLOOD_PRESSURE_DIASTOLIC": ("8462-4", "Diastolic blood pressure"),
    "TEMPERATURE": ("8310-5", "Body temperature"),
    "RESPIRATORY_RATE": ("9279-1", "Respiratory rate"),
    "OXYGEN_SATURATION": ("59408-5", "Oxygen saturation in Arterial blood"),
    "WEIGHT": ("29463-7", "Body weight"),
    "HEIGHT": ("8302-2", "Body height"),
    "GLUCOSE": ("2339-0", "Glucose in Blood"),
}


# ---------------------------------------------------------------------------
# Helpers
# ---------------------------------------------------------------------------

def _iso(dt):
    """Convertit en ISO 8601 (format FHIR)."""
    if dt is None:
        return None
    if isinstance(dt, datetime):
        return dt.isoformat()
    if isinstance(dt, date):
        return dt.isoformat()
    return None


def _gender_fhir(internal):
    """Mapping genre interne (M/F/O) → FHIR (male/female/other/unknown)."""
    if not internal:
        return None
    mapping = {
        "M": "male",
        "F": "female",
        "O": "other",
        "U": "unknown",
    }
    return mapping.get(internal.upper(), "unknown")


def _meta(resource_type, id_, last_updated=None):
    """Construit le bloc `meta` standard."""
    return {
        "versionId": "1",
        "lastUpdated": _iso(last_updated) or _iso(datetime.utcnow()),
        "tag": [
            {
                "system": GUINEECARE_SYSTEM,
                "code": "GUINEECARE",
                "display": "Generated by GuinéeCare Hospital Suite",
            }
        ],
    }


def _reference(resource_type, id_):
    """Construit une référence FHIR (relative URL)."""
    return {"reference": f"{resource_type}/{id_}"}


def _identifier(system, value):
    return {"system": system, "value": value}


def _codeable_concept(system, code, display=None):
    cc = {"coding": [{"system": system, "code": code}]}
    if display:
        cc["coding"][0]["display"] = display
        cc["text"] = display
    return cc


