def measurement_to_fhir(measurement, patient_id):
    """Convertit une constante vitale en ressource FHIR Observation R4.

    Le champ `measurement_type` est mappé vers un code LOINC standard.
    """
    m_type = getattr(measurement, "measurement_type", None) or "UNKNOWN"
    loinc = VITAL_LOINC.get(m_type)
    if not loinc:
        code, display = "0", m_type
    else:
        code, display = loinc

    # Value : essayer de parser en Quantity
    value = getattr(measurement, "value", None)
    unit = getattr(measurement, "unit", None) or ""
    try:
        numeric_value = float(str(value).split()[0])
        value_quantity = {"value": numeric_value, "unit": unit}
    except (ValueError, TypeError):
        value_quantity = {"valueString": str(value)} if value else None

    fhir = {
        "resourceType": "Observation",
        "id": measurement.id,
        "meta": _meta("Observation", measurement.id, getattr(measurement, "recorded_at", None)),
        "status": "final",
        "category": [
            {
                "coding": [{
                    "system": "http://terminology.hl7.org/CodeSystem/observation-category",
                    "code": "vital-signs",
                    "display": "Vital Signs",
                }]
            }
        ],
        "code": _codeable_concept(LOINC_SYSTEM, code, display),
        "subject": _reference("Patient", patient_id),
    }

    measured_at = getattr(measurement, "measured_at", None) or getattr(measurement, "recorded_at", None)
    fhir["effectiveDateTime"] = _iso(measured_at)

    if value_quantity:
        fhir["valueQuantity"] = value_quantity

    return fhir


