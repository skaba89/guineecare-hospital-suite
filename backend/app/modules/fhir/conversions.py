"""Conversions FHIR R4 v1.6.0 — mapping entre modèles internes GuinéeCare et ressources FHIR R4.

Référence : HL7 FHIR R4 (https://hl7.org/fhir/R4/).

Ressources supportées :
- `Patient` → `app.modules.patients.models.Patient`
- `Encounter` → `app.modules.admissions.models.Admission`
- `Observation` → `app.modules.clinical.models.PatientMeasurement` (constantes) +
  `app.modules.laboratory.models.LabResult` (résultats labo)
- `MedicationRequest` → `app.modules.clinical.models.ClinicalNote` (note_type=PRESCRIPTION)
- `DiagnosticReport` → `app.modules.imaging.models.ImagingResult`

Conventions FHIR respectées :
- IDs FHIR = IDs internes (UUIDs).
- `meta.lastUpdated` = `updated_at` ou `created_at` de l'entité interne.
- `identifier` : `patient_number`, `national_id` (avec system distincts).
- `subject` : référence Patient (relative URL `Patient/{id}`).
- `status` : mapping vers les codes FHIR (active/finished/preliminary/final/...).
- Codes LOINC pour les observations labo, SNOMED CT pour les constantes vitales.

Notes :
- Les ressources FHIR sont générées à la volée (pas de cache persistant en v1.6).
- Les tags `meta.tag` incluent `GUINEECARE` pour traçabilité.
"""
