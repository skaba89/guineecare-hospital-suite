def lab_result_to_fhir(lab_result, patient_id):
    """Convertit un résultat de laboratoire en ressource FHIR Observation R4.

    Statuts mappés :
    - PENDING → preliminary
    - VALIDATED → final
    - CANCELLED → cancelled
    - DRAFT → preliminary

    Le modèle LabResult ne contient pas `unit` ni `reference_range` — ces
    informations seraient à chercher dans le LabTest parent (v1.7).
    """
    status = getattr(lab_result, "status", None) or "PENDING"
    status_map = {
        "PENDING": "preliminary",
        "VALIDATED": "final",
        "CANCELLED": "cancelled",
        "DRAFT": "preliminary",
    }
    fhir_status = status_map.get(status.upper(), "unknown")

    fhir = {
        "resourceType": "Observation",
        "id": lab_result.id,
        "meta": _meta("Observation", lab_result.id, getattr(lab_result, "entered_at", None)),
        "status": fhir_status,
        "category": [
            {
                "coding": [{
                    "system": "http://terminology.hl7.org/CodeSystem/observation-category",
                    "code": "laboratory",
                    "display": "Laboratory",
                }]
            }
        ],
        "code": _codeable_concept(LOINC_SYSTEM, "0", "Laboratory result"),
        "subject": _reference("Patient", patient_id),
    }

    # Value
    result_value = getattr(lab_result, "result_value", None)
    if result_value:
        try:
            numeric_value = float(str(result_value).split()[0])
            fhir["valueQuantity"] = {"value": numeric_value}
        except (ValueError, TypeError):
            fhir["valueString"] = str(result_value)

    # Interpretation
    interpretation = getattr(lab_result, "interpretation", None)
    if interpretation:
        interp = interpretation.upper()
        if "CRITIQUE" in interp or "CRITICAL" in interp:
            fhir["interpretation"] = [{
                "coding": [{
                    "system": "http://terminology.hl7.org/CodeSystem/v3-ObservationInterpretation",
                    "code": "HX",
                    "display": "Critical high",
                }]
            }]
        elif "HAUT" in interp or "HIGH" in interp:
            fhir["interpretation"] = [{
                "coding": [{
                    "system": "http://terminology.hl7.org/CodeSystem/v3-ObservationInterpretation",
                    "code": "H",
                    "display": "High",
                }]
            }]
        elif "BAS" in interp or "LOW" in interp:
            fhir["interpretation"] = [{
                "coding": [{
                    "system": "http://terminology.hl7.org/CodeSystem/v3-ObservationInterpretation",
                    "code": "L",
                    "display": "Low",
                }]
            }]

    # Effective date
    entered_at = getattr(lab_result, "entered_at", None)
    validated_at = getattr(lab_result, "validated_at", None)
    if validated_at:
        fhir["effectiveDateTime"] = _iso(validated_at)
    elif entered_at:
        fhir["effectiveDateTime"] = _iso(entered_at)

    return fhir


