def bundle(resources, *, total=None, type_="searchset"):
    """Construit une Bundle FHIR R4 contenant les ressources."""
    return {
        "resourceType": "Bundle",
        "id": f"bundle-{datetime.utcnow().strftime('%Y%m%d%H%M%S')}",
        "type": type_,
        "total": total if total is not None else len(resources),
        "entry": [
            {
                "fullUrl": f"{r['resourceType']}/{r['id']}",
                "resource": r,
            }
            for r in resources
        ],
    }


def operation_outcome(severity, code, diagnostics):
    """Construit une ressource OperationOutcome FHIR pour les erreurs."""
    return {
        "resourceType": "OperationOutcome",
        "issue": [
            {
                "severity": severity,
                "code": code,
                "diagnostics": diagnostics,
            }
        ],
    }
