# Patient → FHIR Patient
# ---------------------------------------------------------------------------

def patient_to_fhir(patient):
    """Convertit un Patient GuinéeCare en ressource FHIR Patient R4.

    Champs mappés :
    - `identifier` : patient_number (obligatoire) + national_id (si présent).
    - `name` : family + given (official use).
    - `gender` : male/female/other/unknown.
    - `birthDate` : YYYY-MM-DD.
    - `telecom` : phone (mobile).
    - `address` : text (concaténation).
    - `active` : true si status == ACTIVE.
    """
    identifiers = [_identifier(PATIENT_NUMBER_SYSTEM, patient.patient_number)]
    if patient.national_id:
        identifiers.append(_identifier(NATIONAL_ID_SYSTEM, patient.national_id))

    fhir = {
        "resourceType": "Patient",
        "id": patient.id,
        "meta": _meta("Patient", patient.id, patient.created_at),
        "identifier": identifiers,
        "name": [
            {
                "use": "official",
                "family": patient.last_name,
                "given": [patient.first_name],
            }
        ],
        "active": patient.status == "ACTIVE",
    }

    gender = _gender_fhir(patient.gender)
    if gender:
        fhir["gender"] = gender

    if patient.date_of_birth:
        fhir["birthDate"] = _iso(patient.date_of_birth)

    if patient.phone:
        fhir["telecom"] = [{"system": "phone", "value": patient.phone, "use": "mobile"}]

    if patient.address:
        fhir["address"] = [{"text": patient.address}]

    if patient.insurance_number:
        fhir.setdefault("identifier", []).append(
            _identifier(f"{GUINEECARE_SYSTEM}/insurance", patient.insurance_number)
        )

    # Contact d'urgence
    if patient.emergency_contact_name or patient.emergency_contact_phone:
        contact = {"relationship": [{"text": "Emergency contact"}]}
        if patient.emergency_contact_name:
            contact["name"] = {"text": patient.emergency_contact_name}
        if patient.emergency_contact_phone:
            contact["telecom"] = [{"system": "phone", "value": patient.emergency_contact_phone}]
        fhir["contact"] = [contact]

    return fhir


